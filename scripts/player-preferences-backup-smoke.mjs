import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../public/games/player-preferences-backup.js', import.meta.url), 'utf8');
const html = readFileSync(new URL('../public/games/index.html', import.meta.url), 'utf8');
const sandbox = { window:{}, Set, Object, String, Number, Math, Array, Boolean, Date, JSON };
vm.runInNewContext(source, sandbox);
const api = sandbox.window.OSGARDPreferencesBackup;
assert.ok(api, 'pure import/export validation helpers are exposed');
const backup = api.createBackup(['cascade-lab','time','cascade-lab'], ['inherit','swarm'], '2026-10-15T00:00:00.000Z');
assert.equal(backup.schema, 'osgard.player-preferences');
assert.equal(backup.schemaVersion, 1);
assert.deepEqual(Array.from(backup.favorites), ['cascade-lab','time']);
assert.deepEqual(Array.from(backup.recent), ['inherit','swarm']);
assert.equal(api.validateBackup(backup).ok, true);
assert.equal(api.validateBackup({ ...backup, schemaVersion:99 }).code, 'schema_invalid');
assert.equal(api.validateBackup({ ...backup, favorites:['../../evil'] }).code, 'favorites_unknown_game');
assert.equal(api.validateBackup({ ...backup, recent:Array(12).fill('time') }).code, 'recent_invalid_list');
assert.equal(api.validateBackup({ schema:'osgard.player-preferences', schemaVersion:1, favorites:['time'] }).code, 'recent_invalid_list');
assert.equal(api.maxFileBytes, 100000);
assert.match(source, /window\.confirm/);
assert.match(source, /file\.size > MAX_FILE_BYTES/);
assert.match(source, /file\.text\(\)/);
assert.match(source, /osgard\.games\.favorites\.v1/);
assert.match(source, /osgard\.games\.recent\.v1/);
assert.doesNotMatch(source, /\bfetch\s*\(|sendBeacon\s*\(|XMLHttpRequest/);
assert.match(source, /window\.location\.reload/);
assert.match(source, /aria-live/);
assert.match(html, /id="catalog-share-state"/);
console.log('PASS collection backup: schema validation, allow-listed IDs, bounded file, overwrite confirmation and local-only import/export.');
