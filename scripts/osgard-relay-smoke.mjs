import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const corePath=resolve('public/games/osgard-relay-core.js');
const relayPath=resolve('public/games/osgard-relay.js');
const cssPath=resolve('public/games/osgard-relay.css');
const html=readFileSync(resolve('public/games/index.html'),'utf8');
const lifecycle=readFileSync(resolve('public/games/player-lifecycle.js'),'utf8');
const consented=readFileSync(resolve('public/games/consented-analytics.js'),'utf8');
const serverCore=readFileSync(resolve('services/osgard-commerce-api/src/core.mjs'),'utf8');
const relaySource=readFileSync(relayPath,'utf8');
const relayCss=readFileSync(cssPath,'utf8');
for(const path of [corePath,relayPath,cssPath])assert.ok(existsSync(path),'Missing Relay runtime asset: '+path);
assert.ok(html.includes('osgard-relay-core.js')&&html.includes('osgard-relay.js')&&html.includes('osgard-relay.css'),'Games hub must include Relay core/runtime/styles');
assert.ok(lifecycle.includes("new CustomEvent('osgard:game-session-started'"),'The player lifecycle must expose only confirmed session starts to Relay');
assert.ok(lifecycle.includes("new CustomEvent('osgard:game-completed'"),'Relay must listen for actual game completion, not player close');
assert.ok(relaySource.includes("document.addEventListener('osgard:game-session-started'")&&relaySource.includes("document.addEventListener('osgard:game-completed'"),'Relay must observe real gameplay lifecycle events');
assert.ok(relaySource.includes("document.addEventListener('osgard:game-session-ended'")&&relaySource.includes('relay_abandoned'),'Closing an incomplete Relay session must be recorded as an abandoned local route');
assert.ok(relaySource.includes("localStorage.setItem(COSMETIC_KEY")&&relaySource.includes('relayTrail: true'),'Relay cosmetic reward must remain explicitly local');
assert.ok(!relaySource.includes('fetch(')&&!relaySource.includes('sendBeacon('),'Relay must use the existing consented analytics queue, not bypass consent');
assert.ok(relaySource.includes("params.get('utm_campaign') !== 'osgard_relay'"),'Invite links must validate campaign context');
assert.ok(relayCss.includes('.og-relay-entry')&&relayCss.includes('.og-relay-choice')&&relayCss.includes('prefers-reduced-motion:reduce'),'Relay must have responsive accessible styling');
for(const name of ['relay_seen','relay_opt_in','relay_game_1_started','relay_milestone_reached','relay_game_2_selected','relay_game_2_started','relay_completed','relay_invite_link_prepared','relay_invite_opened','relay_invite_accepted','relay_abandoned']){
 assert.ok(consented.includes("'"+name+"'"),'Consented client analytics is missing Relay event '+name);
 assert.ok(serverCore.includes('"'+name+'"'),'Commerce API must allow Relay event '+name);
}

await import('../public/games/osgard-relay-core.js');
const core=globalThis.OSGARDRelayCore;
assert.ok(core&&core.version==='1.0.0','Relay core API must load in Node and browser runtimes');
const first=core.createState({id:'a1b2c3d4',firstGame:'null-shift',at:100});
assert.equal(first.phase,'await_first_start');
assert.equal(core.transition(first,{type:'game_completed',game:'null-shift',at:110}).changed,false,'A completion before a real session start must not advance Relay');
const start1=core.transition(first,{type:'session_started',game:'null-shift',at:120});
assert.equal(start1.state.phase,'first_started');
assert.deepEqual(start1.events,['relay_game_1_started']);
assert.equal(core.transition(start1.state,{type:'game_completed',game:'swarm',at:130}).changed,false,'Completion from another title must not advance the first stage');
const milestone=core.transition(start1.state,{type:'game_completed',game:'null-shift',at:140});
assert.equal(milestone.state.phase,'await_second');
assert.deepEqual(milestone.events,['relay_milestone_reached']);
assert.equal(core.transition(milestone.state,{type:'second_selected',game:'remix',at:150}).changed,false,'A second game outside the route map must be rejected');
const choose2=core.transition(milestone.state,{type:'second_selected',game:'swarm',at:160});
assert.equal(choose2.state.phase,'await_second_start');
assert.equal(choose2.state.secondGame,'swarm');
assert.deepEqual(choose2.events,['relay_game_2_selected']);
const wrongStart=core.transition(choose2.state,{type:'session_started',game:'remix',at:170});
assert.equal(wrongStart.state.phase,'abandoned','Starting an unrelated game should abandon, not advance, the route');
assert.deepEqual(wrongStart.events,['relay_abandoned']);
const start2=core.transition(choose2.state,{type:'session_started',game:'swarm',at:180});
assert.equal(start2.state.phase,'second_started');
assert.deepEqual(start2.events,['relay_game_2_started']);
const premature=core.transition(start2.state,{type:'game_completed',game:'null-shift',at:190});
assert.equal(premature.changed,false,'The first game cannot complete the second stage');
const completed=core.transition(start2.state,{type:'game_completed',game:'swarm',at:200});
assert.equal(completed.state.phase,'completed');
assert.equal(completed.rewardUnlocked,true,'Cosmetic reward requires both confirmed gameplay completions');
assert.deepEqual(completed.events,['relay_completed']);
const abandoned=core.transition(start1.state,{type:'session_ended',game:'null-shift',reason:'closed_by_user',at:140});
assert.equal(abandoned.state.phase,'abandoned');
assert.deepEqual(abandoned.events,['relay_abandoned']);
assert.equal(abandoned.rewardUnlocked,false,'Abandoning the chain must not award the cosmetic');
const cancelled=core.transition(first,{type:'cancel',at:145});
assert.equal(cancelled.state.phase,'abandoned','Manual cancellation must abandon the route');
assert.deepEqual(cancelled.events,['relay_abandoned']);
assert.equal(cancelled.rewardUnlocked,false,'Cancelling must not grant the cosmetic');
assert.equal(core.transition(completed.state,{type:'cancel',at:210}).changed,false,'A completed route must not be retroactively cancelled');
assert.ok(relaySource.includes('function cancelRelay(')&&relaySource.includes('Отменить маршрут'),'Users must be able to cancel a pending Relay from the UI');
assert.ok(relayCss.includes('.og-relay-cancel'),'The cancellation control needs a styled accessible target');

assert.deepEqual(core.choices(milestone.state),['swarm','time']);
const invite=core.validateInvite({code:'deadbeef',firstGame:'null-shift',secondGame:'swarm'});
assert.deepEqual(invite,{code:'deadbeef',firstGame:'null-shift',secondGame:'swarm'});
assert.equal(core.validateInvite({code:'bad',firstGame:'null-shift',secondGame:'swarm'}),null);
assert.equal(core.validateInvite({code:'deadbeef',firstGame:'null-shift',secondGame:'remix'}),null);
assert.equal(core.normalizeState({schemaVersion:1,id:'a1b2c3d4',phase:'second_started',firstGame:'null-shift',secondGame:'remix'}),null,'Persisted states must reject invalid first/second pairings');
new Function(relaySource);
console.log('PASS OSGARD Relay: real-start gate, two-stage completion, valid route pairs, consent-gated funnel events, invite schema and local-only cosmetic reward.');
