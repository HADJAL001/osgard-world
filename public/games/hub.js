function updateContinue() {
  const last = recents()[0];
  const game = last ? gameById(last.gameId) : null;
  $("#continue-game").disabled = !game;
  $("#continue-strip").hidden = !game;
  if (!game) return;
  $("#last-game-title").textContent = state.locale === "ru" ? game.title : game.titleEn;
  $("#last-game-summary").textContent = state.locale === "ru" ? game.summary : game.summaryEn;
}
function setFilter(filter) {
  state.filter = filter;
  $$(".filter-pill").forEach(button => {
    const active = button.dataset.filter === filter;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  renderCatalog();
}
function toggleFavorite(id) {
  const current = favorites();
  const existed = current.includes(id);
  const next = existed ? current.filter(value => value !== id) : current.concat(id);
  if (writeLocal(STORAGE.favorites, next)) {
    record(existed ? "game_unfavorited" : "game_favorited", { gameId: id });
    renderCatalog();
  }
}
