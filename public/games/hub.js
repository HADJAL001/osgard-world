function saveRecent(id) {
  const previous = recents().filter(item => item.gameId !== id);
  return writeLocal(STORAGE.recent, [{gameId:id, openedAt:new Date().toISOString()}].concat(previous).slice(0, 20));
}
function openGame(id) {
  const game = gameById(id);
  if (!game || !(game.launchUrl === "/games/time" || game.launchUrl.startsWith("/games/"))) return;
  state.activeGame = game;
  clearTimeout(state.loadTimer);
  $("#launcher-title").textContent = state.locale === "ru" ? game.title : game.titleEn;
  $("#launcher-game-id").textContent = game.id.toUpperCase() + " · " + game.buildType;
  $("#launcher-status").textContent = t("launcher-loading");
  $("#frame-loading").classList.remove("is-hidden");
  $("#launcher-error").hidden = true;
  $("#launcher-new-tab").href = game.launchUrl;
  $("#launcher-retry").href = game.launchUrl;
  $("#game-frame").title = "OSGARD / " + (state.locale === "ru" ? game.title : game.titleEn);
  $("#game-frame").src = "about:blank";
  $("#game-dialog").showModal();
  saveRecent(id);
  updateContinue();
  record("game_opened", { gameId:id, launchUrl:game.launchUrl });
  window.setTimeout(() => { if (state.activeGame && state.activeGame.id === id && $("#game-dialog").open) $("#game-frame").src = game.launchUrl; }, 40);
  state.loadTimer = window.setTimeout(() => {
    if (state.activeGame && state.activeGame.id === id && $("#game-dialog").open && $("#frame-loading").classList.contains("is-hidden")) {
      $("#launcher-status").textContent = t("play-shell-loaded");
    } else if (state.activeGame && state.activeGame.id === id && $("#game-dialog").open) {
      $("#launcher-status").textContent = t("launcher-error-copy");
    }
  }, 12000);
}
function closeGame() {
  if (!$("#game-dialog").open) return;
  const id = state.activeGame ? state.activeGame.id : "";
  $("#game-frame").src = "about:blank";
  $("#game-dialog").close();
  clearTimeout(state.loadTimer);
  state.loadTimer = null;
  if (id) record("game_launcher_closed", {gameId:id});
  state.activeGame = null;
  toast(state.locale === "ru" ? "Игровая оболочка закрыта. История сохранена на этом устройстве." : "Game shell closed. History stays on this device.");
}
async function shareGame(id) {
  const game = gameById(id);
  if (!game) return;
  const title = state.locale === "ru" ? game.title : game.titleEn;
  const summary = state.locale === "ru" ? game.summary : game.summaryEn;
  const url = new URL(game.launchUrl, location.origin).href;
  try {
    if (navigator.share) {
      await navigator.share({title, text:summary, url});
      record("share_created", {gameId:id, medium:"web_share"});
    } else if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(url);
      record("share_created", {gameId:id, medium:"clipboard"});
      toast(t("share-success"));
    } else {
      window.prompt(state.locale === "ru" ? "Скопируй ссылку на игру:" : "Copy the game link:", url);
    }
  } catch (error) {
    if (!error || error.name !== "AbortError") toast(t("share-fail"));
  }
}
