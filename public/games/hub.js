  $("#detail-play").addEventListener("click", () => {
    const id = $("#detail-play").dataset.id;
    $("#game-details").close();
    openGame(id);
  });
  $("#detail-share").addEventListener("click", () => shareGame($("#detail-share").dataset.id));
