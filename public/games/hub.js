const STORAGE = {
  favorites: "osgard.games.favorites.v1",
  recent: "osgard.games.recent.v1",
  analytics: "osgard.games.analytics.v1",
  pending: "osgard.games.pending.v1",
  consent: "osgard.games.analytics-consent.v1"
};
const state = { locale: "ru", catalog: null, filter: "all", search: "", genre: "all", activeGame: null, loadTimer: null, toastTimer: null };
const $ = (selector, root = document) => root.querySelector(selector);
const $$ = (selector, root = document) => Array.from(root.querySelectorAll(selector));
const t = key => COPY[state.locale][key] || COPY.ru[key] || key;
const readLocal = (key, fallback) => { try { const value = JSON.parse(localStorage.getItem(key) || "null"); return value === null ? fallback : value; } catch { return fallback; } };
const writeLocal = (key, value) => { try { localStorage.setItem(key, JSON.stringify(value)); return true; } catch { toast(state.locale === "ru" ? "Не удалось сохранить локальные данные." : "Could not save local data."); return false; } };
const favorites = () => readLocal(STORAGE.favorites, []);
const recents = () => readLocal(STORAGE.recent, []);
const hasConsent = () => localStorage.getItem(STORAGE.consent) === "yes";
function escapeHtml(value) {
  return String(value == null ? "" : value).replace(/[&<>"']/g, char => ({ "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;", "'":"&#39;" }[char]));
}
function record(name, payload = {}) {
  if (!hasConsent()) return;
  const event = {
    id: (crypto.randomUUID && crypto.randomUUID()) || (Date.now() + "-" + Math.random().toString(16).slice(2)),
    name, payload, occurredAt: new Date().toISOString(), schemaVersion: 1
  };
  const events = readLocal(STORAGE.analytics, []);
  events.push(event);
  if (!writeLocal(STORAGE.analytics, events.slice(-300))) return;
  const pending = readLocal(STORAGE.pending, []);
  pending.push(event);
  writeLocal(STORAGE.pending, pending.slice(-50));
  void flushPendingEvents();
}
async function flushPendingEvents() {
  if (!hasConsent()) return;
  let accessToken = "";
  try { accessToken = localStorage.getItem("osgard.auth.accessToken") || ""; } catch { return; }
  if (!accessToken) return;
  const pending = readLocal(STORAGE.pending, []);
  const sentIds = new Set();
  for (const event of pending) {
    if (!hasConsent()) break;
    try {
      const response = await fetch("/api/v1/player/events", {
        method: "POST",
        credentials: "same-origin",
        headers: { "authorization": "Bearer " + accessToken, "content-type": "application/json" },
        body: JSON.stringify({ event })
      });
      if (!response.ok) break;
      sentIds.add(event.id);
    } catch {
      break;
    }
  }
  if (!hasConsent()) {
    try { localStorage.removeItem(STORAGE.pending); } catch {}
    return;
  }
  const latest = readLocal(STORAGE.pending, []);
  writeLocal(STORAGE.pending, latest.filter(event => !sentIds.has(event.id)).slice(-50));
}
function toast(message) {
  const node = $("#toast");
  node.textContent = message;
  node.classList.add("is-visible");
  clearTimeout(state.toastTimer);
  state.toastTimer = setTimeout(() => node.classList.remove("is-visible"), 2600);
}
function genreLabel(tag) {
  const labels = {
    strategy:{ru:"стратегия",en:"strategy"}, simulation:{ru:"симуляция",en:"simulation"},
    "co-op":{ru:"кооператив",en:"co-op"}, tactical:{ru:"тактика",en:"tactical"},
    action:{ru:"экшен",en:"action"}, narrative:{ru:"история",en:"narrative"},
    creation:{ru:"создание",en:"creation"}, challenge:{ru:"испытания",en:"challenges"}
  };
  return labels[tag] ? labels[tag][state.locale] : tag;
}
function applyLocale() {
  document.documentElement.lang = state.locale;
  $$("[data-i18n]").forEach(node => { node.textContent = t(node.dataset.i18n); });
  $$("[data-i18n-placeholder]").forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
  $("#locale-toggle").textContent = state.locale === "ru" ? "RU / EN" : "EN / RU";
  $("#game-search").setAttribute("aria-label", t("search-label"));
  if (state.catalog) { renderCatalog(); renderEcosystem(); }
}
function gameById(id) { return state.catalog ? state.catalog.games.find(game => game.id === id) || null : null; }
function matchesGame(game) {
  if (state.filter === "featured" && !game.featured) return false;
  if (state.filter === "favorites" && !favorites().includes(game.id)) return false;
  if (state.genre !== "all" && !(game.tags || []).includes(state.genre)) return false;
  const query = state.search.trim().toLocaleLowerCase();
  if (!query) return true;
  const searchable = [
    game.title, game.titleEn, game.genre, game.genreEn, game.summary, game.summaryEn,
    game.description, game.descriptionEn, game.buildType, ...(game.tags || [])
  ].join(" ").toLocaleLowerCase();
  return searchable.includes(query);
}
