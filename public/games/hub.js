    '<span class="ecosystem-mark">' + escapeHtml(project.mark) + '</span><span><strong>' + escapeHtml(project.name) + '</strong>' +
    '<p>' + escapeHtml(project.description) + '</p><span class="ecosystem-link">' + escapeHtml(t("ecosystem-open")) + '</span></span></a>'
